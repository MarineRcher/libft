#include <stdlib.h>
#include "libft.h"

char	*ft_strdup(const char *s)
{
	char	*c;
	size_t	i;

	i = 0;
	c = malloc(ft_strlen((char *)s) * sizeof(char));
	if (c == NULL)
		return (NULL);
	while (s[i])
	{
		c[i] = s[i];
		i++;
	}
	c[i] = '\0';
	return (c);
}
